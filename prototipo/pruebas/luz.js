const { chromium } = require('playwright'); const fs = require('fs');
const [dir, pkg] = process.argv.slice(2);
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
  const p = await b.newPage({ viewport: { width: 800, height: 600 } });
  const errs=[]; p.on('pageerror', e => errs.push('PE '+e.message)); p.on('console', m => { if (m.type()==='warning'||m.type()==='error') errs.push(m.text().slice(0,200)); });
  await p.route('**/npm/three@0.147.0/**', r => { const rel = r.request().url().split('three@0.147.0/')[1]; r.fulfill({ path: pkg + '/' + rel, contentType: 'application/javascript' }); });
  await p.route('**fonts.g**', r => r.abort());
  const html = '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"></head><body>' + fs.readFileSync(dir + '/maqueta.html', 'utf8') + '</body></html>';
  await p.route('http://local.test/', r => r.fulfill({ body: html, contentType: 'text/html' }));
  await p.goto('http://local.test/');
  await p.waitForTimeout(5000);
  await p.click('#qual', { noWaitAfter: true }); await p.click('#mode', { noWaitAfter: true });
  await p.mouse.move(150, 300); await p.mouse.down(); await p.mouse.move(600, 300, { steps: 10 }); await p.mouse.up();
  await p.waitForTimeout(2000);
  const st = () => p.evaluate(() => { const G = window.__GAME__; return { cast: G.P.cast, mp: Math.round(G.P.mp), cdLuz: G.P.cds.luz, act: G.P.act, down: G.P.down, gk: !!G.GK, vfx: !!G.VFX, clips: G.GK ? Object.keys(G.GK.acts).length : 0, luz: G.SPELL.luz }; });
  console.log('antes', JSON.stringify(await st()));
  await p.keyboard.press('KeyR'); await p.waitForTimeout(150);
  console.log('tras R', JSON.stringify(await st()));
  await p.waitForTimeout(500); await p.screenshot({ path: dir + '/l-carga.png' });
  await p.waitForTimeout(400); await p.screenshot({ path: dir + '/l-golpe.png' });
  await p.waitForTimeout(300); await p.screenshot({ path: dir + '/l-despues.png' });
  console.log('ERRS', JSON.stringify(errs.filter(e=>!e.includes('ERR_FAILED')&&!e.includes('GPU stall')).slice(0,8)));
  await b.close();
})();
